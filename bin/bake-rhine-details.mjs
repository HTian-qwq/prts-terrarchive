// Run with .node22/bin/node. Produces version-bound normal/coverage data, no GL.
import { readFile, writeFile } from 'node:fs/promises';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { createArrayDetail } from './rhine-detail-baker.ts';
import { detailSignature } from '../ui/rhine/original/detail-signature.ts';
const bytes = await readFile(new URL('../lib/rhine/assets/archive-cassette.glb', import.meta.url));
const asset = await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
asset.scene.updateMatrixWorld(true);
const mesh = asset.scene.getObjectsByProperty('isMesh', true).find(mesh => mesh.material.name.startsWith('Internal_Ceramic'));
const source = mesh.geometry.clone().applyMatrix4(mesh.matrixWorld).scale(1, 1, 1), indices = [], position = source.attributes.position;
for (let i = 0; i < source.index.count; i += 3) {
  const vertices = [source.index.getX(i), source.index.getX(i + 1), source.index.getX(i + 2)];
  if (vertices.every(v => position.getZ(v) > 0.22)) indices.push(...vertices);
}
source.setIndex(indices);
const bake = createArrayDetail('Array_Interior_Lettering', source, mesh.material);
if (!bake) throw new Error('The shallow lettering could not be baked');
const { width, height, data } = bake.texture.image;
const runs = [];
let previous = -1, count = 0;
for (let i = 0; i < data.length; i += 4) {
  const value = (data[i] + data[i + 1] * 256 + data[i + 2] * 65536 + data[i + 3] * 16777216) >>> 0;
  if (value !== previous && count) { runs.push(count, previous); count = 0; }
  previous = value; count++;
}
if (count) runs.push(count, previous);
bake.geometry.computeBoundingBox();
const bounds = bake.geometry.boundingBox;
const payload = { signature: detailSignature(source), width, height, sourceTriangles: indices.length / 3,
  min: bounds.min.toArray(), max: bounds.max.toArray(), runs };
await writeFile(new URL('../ui/rhine/original/array-detail-data.ts', import.meta.url),
  '// Generated by bin/bake-rhine-details.mjs from archive-cassette.glb.\nexport default ' + JSON.stringify(payload) + ';\n');
console.log({ signature: payload.signature, width, height, textureBytes: data.byteLength, encodedRuns: runs.length / 2 });
bake.geometry.dispose(); bake.material.dispose(); bake.texture.dispose(); source.dispose();
