/** Rebuild the committed pure-JavaScript runtime dependencies; no consumer install hook. */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'vite'

const root = fileURLToPath(new URL('../', import.meta.url))
const require = createRequire(import.meta.url)
const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const dependencies = { 'js-yaml': manifest.devDependencies['js-yaml'], zod: manifest.devDependencies.zod }
const packages = Object.fromEntries(Object.entries(dependencies).map(([name, version]) => {
  const path = require.resolve(name + '/package.json')
  if (JSON.parse(readFileSync(path, 'utf8')).version !== version) throw new Error(`Run npm ci to install ${name}@${version}`)
  return [name, dirname(path)]
}))
await build({
  root, configFile: false, publicDir: false,
  build: {
    outDir: 'lib/runtime', emptyOutDir: true, target: 'node22', minify: false,
    lib: {
      entry: { yaml: join(root, 'resources/runtime/yaml.js'), zod: join(root, 'resources/runtime/zod.js') },
      formats: ['es'], fileName: (_format, name) => `${name}.js`,
    },
    rollupOptions: { output: { banner: '// Generated by npm run build:runtime. See ./licenses/ for upstream notices.' } },
  },
})
mkdirSync(join(root, 'lib/runtime/licenses'), { recursive: true })
for (const [name, path] of Object.entries(packages)) {
  copyFileSync(join(path, 'LICENSE'), join(root, 'lib/runtime/licenses', `${name}-MIT.txt`))
}
writeFileSync(join(root, 'lib/runtime/versions.json'), JSON.stringify(dependencies, null, 2) + '\n')
